// 4. MAP LOCALIZED USER INPUT TO CANONICAL OPTION (LANGUAGE-INDEPENDENT DB VALUES)
// ─────────────────────────────────────────────────────────────────────────────
export const mapLocalizedInputToCanonical = (
  input: string,
  options: string[],
  lang: SupportedLanguage
): string | null => {
  if (!input || !input.trim()) return null;
  const clean = input.trim().toLowerCase();

  // 1. Direct match with canonical option
  const direct = options.find(o => o.toLowerCase() === clean);
  if (direct) return direct;

  // 2. Direct match with localized option
  for (const opt of options) {
    const loc = localizeOptionText(opt, lang).toLowerCase();
    if (loc === clean || loc.replace(/[()]/g, ' ').trim() === clean) {
      return opt;
    }
  }

  // 3. Substring match with localized option
  for (const opt of options) {
    const loc = localizeOptionText(opt, lang).toLowerCase();
    const strippedLoc = loc.replace(/[()]/g, ' ');
    const strippedClean = clean.replace(/[()]/g, ' ');
    if (strippedLoc.includes(strippedClean) || strippedClean.includes(strippedLoc)) {
      return opt;
    }
  }

  // 4. Fallback check against all known entries in OPTIONS_MAP
  for (const key in OPTIONS_MAP) {
    const entry = OPTIONS_MAP[key];
    const locVal = (entry[lang] || '').toLowerCase();
    if (locVal && (locVal === clean || clean.includes(locVal) || locVal.includes(clean))) {
      const matchOpt = options.find(o => o.toLowerCase().includes(key) || key.includes(o.toLowerCase()));
      if (matchOpt) return matchOpt;
    }
  }

  // 5. Cross-mode canonical aliases and variations
  for (const [, aliasList] of Object.entries(CANONICAL_ALIASES)) {
    if (aliasList.some(a => clean === a || clean.includes(a) || a.includes(clean))) {
      const matchOpt = options.find(o =>
        aliasList.some(a => o.toLowerCase() === a || o.toLowerCase().includes(a) || a.includes(o.toLowerCase()))
      );
      if (matchOpt) return matchOpt;
    }
  }

  return null;
};

