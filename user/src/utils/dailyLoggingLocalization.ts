export const localizeOptionText = (opt: string, lang: SupportedLanguage = 'en'): string => {
  if (!opt) return opt;
  if (lang === 'en') return opt;

  const clean = opt.trim().toLowerCase();
  // Exact match
  if (OPTIONS_MAP[clean]) {
    return OPTIONS_MAP[clean][lang] || opt;
  }

  // Substring matching against known keys
  for (const key in OPTIONS_MAP) {
    if (clean === key || (key.length > 5 && (clean.includes(key) || key.includes(clean)))) {
      return OPTIONS_MAP[key][lang] || opt;
    }
  }

  // Number with hrs/hours/mins
  const numHrs = opt.match(/^(\d+(\.\d+)?)\s*(hrs?|hours?)$/i);
  if (numHrs) {
    const n = numHrs[1];
    if (lang === 'ta') return `${n} மணிநேரம்`;
    if (lang === 'kn') return `${n} ಗಂಟೆಗಳು`;
    if (lang === 'hi') return `${n} घंटे`;
    if (lang === 'te') return `${n} గంటలు`;
  }

  return opt;
};

