export type SupportedLanguage = 'en' | 'ta' | 'kn' | 'hi' | 'te';

export const normalizeLang = (lang?: string): SupportedLanguage => {
  if (!lang) return 'en';
  const l = lang.toLowerCase().trim();
  if (l === 'ta' || l.startsWith('tam')) return 'ta';
  if (l === 'kn' || l.startsWith('kan')) return 'kn';
  if (l === 'hi' || l.startsWith('hin')) return 'hi';
  if (l === 'te' || l.startsWith('tel')) return 'te';
  return 'en';
};

