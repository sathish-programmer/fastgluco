const languages = ['en', 'ta', 'te', 'kn', 'hi'];

for (const lang of languages) {
  const filePath = path.join(process.cwd(), `src/i18n/locales/${lang}.ts`);
  let content = fs.readFileSync(filePath, 'utf8');

  let added = 0;
  for (const [key, transObj] of Object.entries(MASTER_TRANSLATIONS)) {
    const val = transObj[lang] || transObj['en'];
    const escapedVal = val.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
    
    // Check if key exists flatly in file
    const flatRegex = new RegExp(`"${key.replace(/\./g, '\\.')}"\\s*:`, 'g');
    if (!flatRegex.test(content)) {
      // Find the last closing brace and insert before it
      const lastBrace = content.lastIndexOf('} as const;') !== -1 
        ? content.lastIndexOf('} as const;') 
        : content.lastIndexOf('};');
      if (lastBrace !== -1) {
        const insertion = `  "${key}": "${escapedVal}",\n`;
        content = content.slice(0, lastBrace) + insertion + content.slice(lastBrace);
        added++;
      }
    }
  }

  fs.writeFileSync(filePath, content, 'utf8');
  console.log(`Updated ${lang}.ts: added ${added} keys.`);
}
